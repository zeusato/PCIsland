// Every app command must be granted to a window through a capability, which keeps
// remote web pages limited to `web_player_report` (docs/02-system-design.md §12).
//
// Single source of truth: the `generate_handler![...]` list in src/lib.rs. From it we
// derive the app manifest and the `app-commands` permission set used by local windows.

const REMOTE_ONLY: &[&str] = &["web_player_report"];

fn main() {
    println!("cargo:rerun-if-changed=src/lib.rs");
    let lib = std::fs::read_to_string("src/lib.rs").expect("read src/lib.rs");
    let start = lib
        .find("generate_handler![")
        .expect("generate_handler! in lib.rs");
    let body = &lib[start
        ..lib[start..]
            .find(']')
            .map(|e| start + e)
            .expect("closing ]")];
    let commands: Vec<&'static str> = body
        .lines()
        .skip(1)
        .filter_map(|l| l.trim().trim_end_matches(',').rsplit("::").next())
        .filter(|c| !c.is_empty())
        .map(|c| &*Box::leak(c.to_owned().into_boxed_str()))
        .collect();

    let local: Vec<String> = commands
        .iter()
        .filter(|c| !REMOTE_ONLY.contains(c))
        .map(|c| format!("  \"allow-{}\",", c.replace('_', "-")))
        .collect();
    let set = format!(
        "# Generated by build.rs from src/lib.rs. Do not edit.\n[[set]]\nidentifier = \"app-commands\"\ndescription = \"Every app command available to local windows.\"\npermissions = [\n{}\n]\n",
        local.join("\n")
    );
    std::fs::create_dir_all("permissions").expect("permissions dir");
    let path = "permissions/app-commands.toml";
    if std::fs::read_to_string(path).ok().as_deref() != Some(set.as_str()) {
        std::fs::write(path, set).expect("write permission set");
    }

    let commands: &'static [&'static str] = Box::leak(commands.into_boxed_slice());
    tauri_build::try_build(
        tauri_build::Attributes::new()
            .app_manifest(tauri_build::AppManifest::new().commands(commands)),
    )
    .expect("failed to run tauri-build");
}
